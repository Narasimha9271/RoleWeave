import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
await mkdir('test-results',{recursive:true});
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
// Run against an isolated local-preview instance with test data only.
await page.goto(process.env.TEST_BASE_URL||'http://127.0.0.1:3001');
await page.getByRole('heading',{name:'Your next chapter starts here.'}).waitFor();
await page.screenshot({path:'test-results/dashboard.png',fullPage:true});
await page.getByRole('button',{name:'My resume',exact:true}).click();
await page.getByRole('button',{name:'Try an example resume'}).click();
await page.getByRole('button',{name:'Save master resume'}).click();
await page.getByRole('button',{name:'Resume studio',exact:true}).click();
await page.getByRole('button',{name:'Use example',exact:true}).click();
await page.getByRole('button',{name:'Generate tailored draft'}).click();
await page.getByRole('button',{name:'Continue without GitHub projects'}).click();
await page.getByRole('textbox',{name:'Tailored resume'}).waitFor();
assert.ok((await page.getByRole('textbox',{name:'Tailored resume'}).inputValue()).includes('Alex Morgan'));
await page.getByRole('button',{name:'Gaps',exact:true}).click();
await page.getByRole('heading',{name:'Room to grow.'}).waitFor();
await page.getByRole('button',{name:'Resume',exact:true}).click();
await page.getByRole('button',{name:'Save application',exact:true}).click();
await page.getByRole('status').filter({hasText:'Application saved'}).waitFor();
await page.getByRole('button',{name:/^Applications/}).click();
await page.getByRole('combobox',{name:'Status for Example Company'}).selectOption('Applied');
await page.reload();
await page.getByRole('button',{name:/^Applications/}).click();
assert.equal(await page.getByRole('combobox',{name:'Status for Example Company'}).inputValue(),'Applied');
await page.getByRole('button',{name:'View resume'}).click();
assert.equal(await page.getByLabel('Company name').inputValue(),'Example Company');
await page.screenshot({path:'test-results/studio.png',fullPage:true});
await page.emulateMedia({media:'print'});await page.pdf({path:'test-results/test-resume.pdf',format:'A4'});await page.emulateMedia({media:'screen'});
await page.setViewportSize({width:390,height:844});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
await page.screenshot({path:'test-results/mobile.png',fullPage:true});
await page.getByRole('button',{name:'Toggle navigation'}).click();
await page.getByRole('button',{name:'Overview',exact:true}).click();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
assert.deepEqual(errors,[]);
console.log('PASS: generation, gap feedback, save, status, persistence, reopen, PDF export, mobile layout; no page errors.');
await browser.close();

